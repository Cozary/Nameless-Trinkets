    @SubscribeEvent
    public static void triggerDamageReflection(LivingDamageEvent.Post event) {

        if (event.getEntity() instanceof Player player) {

            MissingPageHandler.triggerDamageReflection(player, event.getSource(), event.getEntity());
        }
    }

